// Compiles one section for the editor's canvas, using the SAME compiler the build
// uses. This is the whole reason the editor has no renderer of its own.
//
// Every visual editor has to solve preview fidelity, and the usual answers are bad:
// re-implement the renderer in the browser (two renderers, guaranteed to drift), or
// approximate it (the preview lies). Running the real compiler over an endpoint means
// what the owner drags is what the build will emit, because it is the same function.

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { verifyRequestSession } from './lib/auth.mjs';
import { compileSection, scalePx } from '../../src/lib/canvas-compile.mjs';
import { renderImage, loadSections, applyTextEdits, applyAttrEdits, applyImageEdits, applyGroupOrder, buildFooter } from '../../src/render.mjs';
import { validateSite } from '../../src/lib/site-schema.mjs';

const json = (body, status = 200) => new Response(JSON.stringify(body), {
  status, headers: { 'Content-Type': 'application/json' }
});

function loadImageContext() {
  const root = process.cwd();
  const content = JSON.parse(readFileSync(resolve(root, 'src/data/content.json'), 'utf8'));
  const manifest = JSON.parse(readFileSync(resolve(root, 'src/data/responsive-manifest.json'), 'utf8'));
  return { content, manifest };
}

export default async (request) => {
  // This used to refuse outside local mode, because saving committed to GitHub and a
  // commit spends a deploy. That guard has been replaced by the real one: saves now
  // write a draft and only Publish commits. Rendering is read-only and free.
  if (!verifyRequestSession(request)) return json({ error: 'not authenticated' }, 401);
  if (request.method !== 'POST') return json({ error: 'method not allowed' }, 405);

  let section;
  let legacy;
  let draftContent;
  try {
    ({ section, legacy, content: draftContent } = await request.json());
  } catch {
    return json({ error: 'invalid request body' }, 400);
  }

  const loaded = loadImageContext();
  const manifest = loaded.manifest;
  // The editor sends what it currently has, unsaved edits and all. Reading content.json
  // from disk instead would mean the preview could only ever show the last SAVED state,
  // so typing into a field would appear to do nothing until you pressed Save.
  const content = draftContent && draftContent.text
    ? { ...loaded.content, ...draftContent }
    : loaded.content;

  // A hand-built section. These are the nine templates the site has always shipped —
  // real HTML that survived several rounds of design review — and they are rendered
  // here exactly as the build renders them, content and all. Nothing is converted.
  //
  // They do not need converting to be editable: they already carry data-edit and
  // data-img hooks bound to content.json, and the build already substitutes through
  // them. Surfacing those hooks in this editor is a fraction of the work of rebuilding
  // the sections as canvas elements, and it cannot regress a design nobody re-drew.
  if (legacy) {
    // The footer is generated by buildFooter, not one of the nine template files, so it
    // has no raw HTML to run applyTextEdits over — it renders straight from content,
    // exactly the way the build's own footer does.
    if (legacy === 'footer') {
      return json({ html: buildFooter({ content }), css: '', errors: [], warnings: [], legacy: true });
    }
    const { sections } = loadSections(process.cwd());
    const raw = sections[legacy] || (legacy === 'hero' ? loadSections(process.cwd()).prelude : null);
    if (!raw) return json({ error: 'unknown section "' + legacy + '"' }, 404);
    let html = applyTextEdits(raw, content.text);
    html = applyAttrEdits(html, content.text);
    html = applyImageEdits(html, content.images, manifest);
    // Last, same as every build path — so the editor's preview reorders exactly like the
    // real build and the owner never sees a lying canvas.
    html = applyGroupOrder(html, content.order);
    return json({ html, css: '', errors: [], warnings: [], legacy: true });
  }

  if (!section || !section.id) return json({ error: 'no section supplied' }, 400);
  const warnings = [];
  const ctx = {
    scalePx,
    warn: (m) => warnings.push(m),
    legacy: () => '',
    renderImage: (key, alt, opts = {}) => {
      const image = content.images[key];
      if (!image || !manifest[key]) return null;
      const local = { images: { [key]: { ...image, alt: alt || image.alt } } };
      return renderImage(key, local, manifest, {
        loading: opts.priority ? 'eager' : 'lazy',
        fetchpriority: opts.priority ? 'high' : 'auto',
        sizes: '(max-width: 750px) 92vw, 45vw'
      });
    }
  };

  // Validation errors are returned rather than thrown. The editor is where a half-built
  // element legitimately exists — an image the owner has not written alt text for yet
  // is a warning to show in the inspector, not a reason to refuse to draw the canvas.
  // The BUILD is where the same errors are fatal. Same check, different consequence.
  const out = compileSection(section, ctx);

  // The same validator the save endpoint runs, on the same shape, reported live.
  // Dragging an element off the canvas edge renders perfectly well but fails
  // validateBox — so without this the owner only found out at Save, by which point the
  // offending element was off-screen and hard to find. Reusing the validator rather
  // than re-checking here is the point: one definition of "valid", two moments.
  const shapeErrors = validateSite({
    pages: [{ id: 'preview', path: '/preview', title: 'preview', sections: [section] }]
  }).filter((e) => !/^page "preview"/.test(e) || /element/.test(e));

  return json({
    html: out.html,
    css: out.css,
    errors: [...out.errors, ...shapeErrors],
    warnings
  });
};
